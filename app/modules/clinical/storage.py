"""Where uploaded reports' bytes live: Part A's own document store (spec section 9.6).

Files do not belong in Postgres rows, and do belong somewhere every Part A process that
reads them can reach: the API (upload) and the Celery worker (text extraction). The store is
Part A's alone (D-19). An upload writes the file first and the row last, so a failed upload
can leave an orphan file (swept later), never a row that names nothing.

**As built: a directory on a volume, not MinIO.** The spec named MinIO; its container images
could not be pulled from Docker Hub or Quay when this was built (2026-11-10, "pull access
denied" / 401). The interface is what the code depends on, so an S3 adapter is one more class
with `put` and `get`, and nothing else changes.

Keys are generated by Part A (`patients/<patient>/<uuid>`), never taken from a filename, and
are checked to stay inside the root, so no key can reach outside the store.
"""

from __future__ import annotations

import asyncio
from pathlib import Path
from typing import Protocol

from app.settings import Settings


class DocumentStore(Protocol):
    async def put(self, key: str, data: bytes, media_type: str) -> None: ...
    async def get(self, key: str) -> bytes: ...


class FilesystemDocumentStore:
    def __init__(self, root: Path) -> None:
        self._root = root.resolve()

    @classmethod
    def from_settings(cls, settings: Settings) -> FilesystemDocumentStore:
        return cls(Path(settings.documents_path))

    def _path(self, key: str) -> Path:
        path = (self._root / key).resolve()
        if self._root not in path.parents:
            raise ValueError(f"document key {key!r} escapes the store")
        return path

    async def put(self, key: str, data: bytes, media_type: str) -> None:
        path = self._path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = path.with_suffix(".part")
            temporary.write_bytes(data)
            temporary.replace(path)  # atomic: a reader never sees half a file

        await asyncio.to_thread(write)

    async def get(self, key: str) -> bytes:
        return await asyncio.to_thread(self._path(key).read_bytes)


class InMemoryDocumentStore:
    def __init__(self) -> None:
        self.objects: dict[str, bytes] = {}

    async def put(self, key: str, data: bytes, media_type: str) -> None:
        self.objects[key] = data

    async def get(self, key: str) -> bytes:
        return self.objects[key]
