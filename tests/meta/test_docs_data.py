"""The documentation site's data is the code's, not a copy that drifts.

`docs/data/*.json` (the API reference, every table, the event/task/workflow catalogue) is
generated by `scripts/gen_docs_data.py`. This runs it with `--check` and fails when the
committed files differ -- so a new endpoint, column, topic, consumer, task or workflow
cannot ship without the site showing it. Fix: `python scripts/gen_docs_data.py`, commit.

In a fresh interpreter, not in-process: unit tests define throwaway models on the shared
`Base`, and in a full run those leak into its metadata and look like extra tables.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]

pytestmark = pytest.mark.meta


def test_the_sites_generated_data_matches_the_code():
    done = subprocess.run(
        [sys.executable, "scripts/gen_docs_data.py", "--check"],
        cwd=ROOT, capture_output=True, text=True, timeout=300,
    )
    assert done.returncode == 0, (
        f"{done.stdout}{done.stderr}\n"
        "docs/data is out of date with the code: run `python scripts/gen_docs_data.py` "
        "and commit the result"
    )
